# COMMAND ----------

chunks = spark.table(f"{FQ}.manual_chunks").select("chunk_id", "source", "page", "text").toPandas()
chunks = chunks[chunks["text"].str.split().str.len() >= MIN_CHUNK_WORDS].reset_index(drop=True)
sample = chunks.sample(n=min(N, len(chunks)), random_state=SEED).reset_index(drop=True)
print(f"{len(chunks)} usable chunks; evaluating {len(sample)}")

# COMMAND ----------

from mlflow.deployments import get_deploy_client

PROMPT = (
    "Read the excerpt of a technical manual and write ONE question that a maintenance technician would "
    "ask and that the excerpt answers. Rules: do not copy sentences verbatim, do not mention 'the excerpt' "
    "or 'the text', a single line, in the same language as the excerpt. Reply with the question only.\n\n"
    "Excerpt:\n{text}"
)


def response_text(resp) -> str:
    """Text of a chat response; some models return a list of content blocks."""
    msg = resp["choices"][0]["message"]["content"]
    if isinstance(msg, list):
        msg = " ".join(
            b.get("text", "") for b in msg if isinstance(b, dict) and b.get("type") in (None, "text")
        )
    return str(msg).strip().strip('"').splitlines()[0].strip() if str(msg).strip() else ""


def llm_question(text: str) -> str | None:
    """A question generated by the LLM, None if it is too short, "ERROR" if the endpoint failed."""
    try:
        cli = get_deploy_client("databricks")
        r = cli.predict(
            endpoint=LLM,
            inputs={
                "messages": [{"role": "user", "content": PROMPT.format(text=text[:3000])}],
                "max_tokens": 400,
                "temperature": 0.2,
            },
        )
        q = response_text(r)
        return q if len(q.split()) >= MIN_QUESTION_WORDS else None
    except Exception as e:
        print("LLM unavailable or error:", type(e).__name__, str(e)[:120])
        return "ERROR"


df_freq = doc_frequency(chunks["text"].tolist())
questions, sources = [], []
llm_ok = USE_LLM
for t in sample["text"]:
    q = None
    if llm_ok:
        q = llm_question(t)
        if q == "ERROR":  # one failure disables the LLM for the rest (avoids N identical errors)
            llm_ok, q = False, None
    if q:
        questions.append(q)
        sources.append("llm")
    else:
        questions.append(extractive_question(t, df_freq, len(chunks)))
        sources.append("extractive")
sample["question"], sample["question_source"] = questions, sources
print(sample["question_source"].value_counts().to_string())
display(sample[["source", "page", "question", "question_source"]].head(10))

# COMMAND ----------

from databricks.ai_search.client import AISearchClient

index = AISearchClient().get_index(endpoint_name=ENDPOINT, index_name=INDEX)
rankings = []
for q in sample["question"]:
    r = index.similarity_search(query_text=q, columns=["chunk_id"], num_results=max(KS), query_type=QTYPE)
    rankings.append([row[0] for row in r["result"]["data_array"]])
sample["retrieved"] = [",".join(r) for r in rankings]
metrics = evaluate_retrieval(rankings, [{cid} for cid in sample["chunk_id"]], ks=KS)
print({k: round(v, 3) if isinstance(v, float) else v for k, v in metrics.items()})

# COMMAND ----------

import mlflow

current_user = spark.sql("SELECT current_user()").first()[0]
mlflow.set_experiment(f"/Users/{current_user}/predictive_maintenance_rag_eval")
with mlflow.start_run(run_name=f"retrieval_{QTYPE.lower()}"):
    mlflow.log_params(
        {
            "index": INDEX,
            "query_type": QTYPE,
            "n_questions": len(sample),
            "generator": "llm:" + LLM if llm_ok else "extractive",
            "n_chunks_index": len(chunks),
            "k_max": max(KS),
        }
    )
    mlflow.log_metrics({k: float(v) for k, v in metrics.items()})
    mlflow.log_table(
        sample[["chunk_id", "source", "page", "question", "question_source", "retrieved"]],
        artifact_file="eval_retrieval.json",
    )

# Persistent table, so that it can be queried from SQL or a dashboard.
