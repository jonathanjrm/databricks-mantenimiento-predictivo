# MAGIC # 05. RAG retrieval evaluation
# MAGIC
# MAGIC Measures whether the index retrieves the right chunk. The evaluation set **is generated from
# MAGIC the chunks themselves** (nothing is written by hand):
# MAGIC
# MAGIC 1. N chunks are sampled (fixed seed).
# MAGIC 2. A Foundation Model APIs LLM writes a question that the chunk answers. If the LLM is not
# MAGIC    available, an extractive fallback is used (rarest terms of the most informative sentence).
# MAGIC 3. The index is queried with the question and the rank of the source chunk is recorded.
# MAGIC
# MAGIC Metrics: **recall@k** (the chunk is among the first k) and **MRR** (mean reciprocal rank).
# MAGIC They are logged to MLflow together with the question table.
# MAGIC
# MAGIC Honest limits: (a) relevance is strict (only the source chunk counts; a neighbouring chunk
# MAGIC from the overlap would also answer), so the figures are a floor; (b) extractive questions
# MAGIC share vocabulary with the chunk and favour lexical search; (c) this measures retrieval, not
# MAGIC the quality of the generated answer.

